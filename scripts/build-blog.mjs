// Builds the LatexDo blog at /blogpost/ from the Markdown files in content/blogpost/.
// Each post is served at /blogpost/<year>/<slug>/, each year has an archive page,
// and /blogpost/feed.xml is the RSS feed. Pages use the shared site template.
//
// A line holding only `::demo <id>` embeds a live editor demo played by
// assets/blog-demos.js (see src/blog-demos.ts for the available ids).
import { mkdirSync, readFileSync, readdirSync, rmdirSync, unlinkSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const contentDirectory = join(root, "content", "blogpost");
const outputDirectory = join(root, "blogpost");
const template = readFileSync(join(root, "scripts/volunteer-page.template.html"), "utf8");
const marker = "<!-- Generated by scripts/build-blog.mjs. Edit content/blogpost/. -->";
const site = "https://latexdo.org";
const blogName = "LatexDo Blog";
const blogDescription =
  "Notes from the LatexDo team: releases, how the editor and its AI work, and LaTeX writing workflows, written up as short readable posts.";
const demoIds = new Set(["ghost", "reformulate", "fix", "mention", "figure"]);

const escape = (value) => String(value).replace(/[&<>"']/g, (char) => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
})[char]);
const dateLabel = new Intl.DateTimeFormat("en-US", { year: "numeric", month: "long", day: "numeric", timeZone: "UTC" });

function slugify(value) {
  return String(value)
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

// Front matter: `key: value` and `key:` followed by `- item` lines.
function parseFrontMatter(source, file) {
  const match = source.replace(/^﻿/, "").match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) throw new Error(`${file} is missing front matter.`);
  const data = {};
  let listKey = null;
  for (const line of match[1].split(/\r?\n/)) {
    const pair = line.match(/^([A-Za-z][\w-]*):\s*(.*)$/);
    if (pair) {
      const value = pair[2].trim().replace(/^(["'])(.*)\1$/, "$2");
      listKey = value ? null : pair[1];
      data[pair[1]] = value ? (value === "true" ? true : value === "false" ? false : value) : [];
      continue;
    }
    const item = line.match(/^\s*-\s+(.*)$/);
    if (item && listKey) data[listKey].push(item[1].trim().replace(/^(["'])(.*)\1$/, "$2"));
  }
  return { data, body: source.slice(match[0].length).trim() };
}

function stripMarkdown(value) {
  return String(value)
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/^::demo .*$/gm, " ")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/[#>*_`|-]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function renderInline(source) {
  const stash = [];
  const keep = (html) => `\u0000${stash.push(html) - 1}\u0000`;
  let html = String(source).replace(/`([^`\n]+)`/g, (_, code) => keep(`<code>${escape(code)}</code>`));
  html = escape(html)
    .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, label, href) => {
      const url = href.replaceAll("&amp;", "&");
      if (/^(javascript|data):/i.test(url)) return label;
      const external = /^https?:\/\//.test(url) && !url.startsWith(site);
      return keep(`<a href="${escape(url)}"${external ? ' rel="noopener"' : ""}>${label}</a>`);
    })
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
    .replace(/(^|[\s(])\*([^*\s][^*]*?)\*/g, "$1<em>$2</em>");
  return html.replace(/\u0000(\d+)\u0000/g, (_, index) => stash[Number(index)]);
}

const tableCells = (line) => line.trim().replace(/^\||\|$/g, "").split("|").map((cell) => cell.trim());
const isTableRule = (line) => /^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)*\|?\s*$/.test(line ?? "");

function renderMarkdown(markdown, demos) {
  const lines = markdown.replace(/\r\n/g, "\n").split("\n");
  const html = [];
  const toc = [];
  const ids = new Map();
  const startsBlock = (line, next) =>
    !line.trim() || /^(```|#{1,6}\s|>\s?|[-*+]\s|\d+\.\s|::demo\s)/.test(line.trim()) || (line.includes("|") && isTableRule(next));

  for (let index = 0; index < lines.length;) {
    const line = lines[index];
    const trimmed = line.trim();
    if (!trimmed) { index += 1; continue; }

    const demo = trimmed.match(/^::demo\s+([a-z-]+)$/);
    if (demo) {
      if (!demoIds.has(demo[1])) throw new Error(`Unknown demo "${demo[1]}".`);
      demos.add(demo[1]);
      html.push(`<figure class="blog-demo" data-demo="${demo[1]}"><noscript><p>This demo plays in the browser with JavaScript turned on.</p></noscript></figure>`);
      index += 1;
      continue;
    }

    const fence = trimmed.match(/^```([\w-]*)$/);
    if (fence) {
      const code = [];
      for (index += 1; index < lines.length && !lines[index].trim().startsWith("```"); index += 1) code.push(lines[index]);
      index += 1;
      html.push(`<pre class="lx-code"><code>${escape(code.join("\n"))}</code></pre>`);
      continue;
    }

    const heading = trimmed.match(/^(#{1,6})\s+(.+)$/);
    if (heading) {
      // The page title is the only h1; Markdown headings start at h2.
      const level = Math.min(6, Math.max(2, heading[1].length));
      const base = slugify(stripMarkdown(heading[2])) || "section";
      const count = ids.get(base) ?? 0;
      ids.set(base, count + 1);
      const id = count ? `${base}-${count + 1}` : base;
      if (level === 2) toc.push({ id, text: stripMarkdown(heading[2]) });
      html.push(`<h${level} id="${id}">${renderInline(heading[2])}</h${level}>`);
      index += 1;
      continue;
    }

    if (line.includes("|") && isTableRule(lines[index + 1])) {
      const head = tableCells(line);
      const rows = [];
      for (index += 2; index < lines.length && lines[index].includes("|"); index += 1) rows.push(tableCells(lines[index]));
      html.push(`<div class="lx-table-wrap"><table class="lx-table"><thead><tr>${head.map((cell) => `<th scope="col">${renderInline(cell)}</th>`).join("")}</tr></thead><tbody>${rows
        .map((row) => `<tr>${row.map((cell) => `<td>${renderInline(cell)}</td>`).join("")}</tr>`).join("")}</tbody></table></div>`);
      continue;
    }

    if (/^>\s?/.test(trimmed)) {
      const quote = [];
      for (; index < lines.length && /^>\s?/.test(lines[index].trim()); index += 1) quote.push(lines[index].trim().replace(/^>\s?/, ""));
      html.push(`<blockquote>${renderMarkdown(quote.join("\n"), demos).html}</blockquote>`);
      continue;
    }

    const list = trimmed.match(/^([-*+]|\d+\.)\s+/);
    if (list) {
      const ordered = /\d/.test(list[1]);
      const pattern = ordered ? /^\d+\.\s+(.+)$/ : /^[-*+]\s+(.+)$/;
      const items = [];
      for (let item; index < lines.length && (item = lines[index].trim().match(pattern)); index += 1) items.push(`<li>${renderInline(item[1])}</li>`);
      html.push(`<${ordered ? "ol" : "ul"}>${items.join("")}</${ordered ? "ol" : "ul"}>`);
      continue;
    }

    const paragraph = [trimmed];
    for (index += 1; index < lines.length && !startsBlock(lines[index], lines[index + 1]); index += 1) paragraph.push(lines[index].trim());
    html.push(`<p>${renderInline(paragraph.join(" "))}</p>`);
  }
  return { html: html.join("\n"), toc };
}

function loadPosts() {
  const posts = [];
  for (const name of readdirSync(contentDirectory).filter((file) => file.endsWith(".md")).sort()) {
    const file = relative(root, join(contentDirectory, name));
    const { data, body } = parseFrontMatter(readFileSync(join(contentDirectory, name), "utf8"), file);
    if (data.draft === true && process.env.BUILD_DRAFTS !== "true") continue;
    for (const field of ["title", "description", "date"]) {
      if (typeof data[field] !== "string" || !data[field].trim()) throw new Error(`${file}: ${field} is required.`);
    }
    if (!/^\d{4}-\d{2}-\d{2}$/.test(data.date)) throw new Error(`${file}: date must be YYYY-MM-DD.`);
    const title = data.title.trim();
    const description = data.description.trim();
    if (`${title} - LatexDo`.length > 60) throw new Error(`${file}: title is too long for search results (max 50 characters).`);
    if (description.length < 70 || description.length > 165) throw new Error(`${file}: description must be 70-165 characters.`);
    const slug = slugify(data.slug || name.replace(/\.md$/, "").replace(/^\d{4}-\d{2}-\d{2}-/, ""));
    const year = data.date.slice(0, 4);
    const demos = new Set();
    const rendered = renderMarkdown(body, demos);
    posts.push({
      file, title, description, slug, year, demos,
      date: data.date,
      dateLabel: dateLabel.format(new Date(`${data.date}T00:00:00Z`)),
      author: String(data.author || "LatexDo"),
      tags: Array.isArray(data.tags) ? data.tags : [],
      path: `/blogpost/${year}/${slug}/`,
      minutes: Math.max(1, Math.round(stripMarkdown(body).split(" ").length / 220)),
      ...rendered,
    });
  }
  const paths = new Set();
  for (const post of posts) {
    if (paths.has(post.path)) throw new Error(`Two posts would be published at ${post.path}.`);
    paths.add(post.path);
  }
  return posts.sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));
}

const jsonLd = (graph) => JSON.stringify({ "@context": "https://schema.org", "@graph": graph }, null, 2).replace(/</g, "\\u003c");
const breadcrumb = (items) => ({
  "@type": "BreadcrumbList",
  itemListElement: items.map(([name, path], index) => ({ "@type": "ListItem", position: index + 1, name, item: `${site}${path}` })),
});

function page({ path, title, description, content, graph, article = false, demos = false }) {
  const values = { title: escape(title), description: escape(description), path: escape(path), content, jsonld: jsonLd(graph) };
  let html = template
    .replace("<!doctype html>", `<!doctype html>\n${marker}`)
    .replace(/\{\{(title|description|path|content|jsonld)\}\}/g, (_, key) => values[key])
    .replace(
      '<link rel="stylesheet" href="/assets/pages.css" />',
      `<link rel="stylesheet" href="/assets/pages.css" />
    <link rel="stylesheet" href="/assets/blog.css" />
    <link rel="alternate" type="application/rss+xml" title="${blogName}" href="${site}/blogpost/feed.xml" />`,
    )
    .replace('<main id="content" class="lx">', '<main id="content" class="lx blog">');
  if (article) html = html.replace('<meta property="og:type" content="website" />', '<meta property="og:type" content="article" />');
  if (demos) {
    html = html.replace(
      '<script type="module" src="/assets/site.js"></script>',
      '<script type="module" src="/assets/site.js"></script>\n    <script type="module" src="/assets/blog-demos.js"></script>',
    );
  }
  return html;
}

const tagList = (tags) => (tags.length ? `<ul class="lx-tags" aria-label="Tags">${tags.map((tag) => `<li>${escape(tag)}</li>`).join("")}</ul>` : "");
const meta = (post) => `<time datetime="${post.date}">${post.dateLabel}</time> · ${post.minutes} min read`;
const card = (post) => `
        <article class="lx-row blog-card reveal">
          <p class="lx-num">${meta(post)}</p>
          <h2><a href="${post.path}">${escape(post.title)}</a></h2>
          <div class="lx-row-body">
            <p>${escape(post.description)}</p>
            ${tagList(post.tags)}
            <a class="lx-arrow" href="${post.path}" aria-label="Read ${escape(post.title)}">Read the post</a>
          </div>
        </article>`;

function listing(heading, lede, posts, years, currentYear) {
  const archive = years.length
    ? `<nav class="blog-years" aria-label="Posts by year">
          <a href="/blogpost/"${currentYear ? "" : ' aria-current="page"'}>All</a>
          ${years.map((year) => `<a href="/blogpost/${year}/"${year === currentYear ? ' aria-current="page"' : ""}>${year}</a>`).join("")}
        </nav>`
    : "";
  return `
      <header class="lx-hero">
        ${currentYear ? '<a class="lx-back" href="/blogpost/">All posts</a>' : ""}
        <p class="lx-label">Blog</p>
        <h1>${heading}</h1>
        <p class="lx-lede">${lede}</p>
        ${archive}
      </header>
      <section class="lx-rows" aria-label="Posts">
${posts.map(card).join("\n")}
      </section>
      <p class="blog-feed"><a class="lx-arrow" href="/blogpost/feed.xml">Follow with RSS</a></p>`;
}

function postPage(post, posts) {
  const index = posts.indexOf(post);
  const newer = posts[index - 1];
  const older = posts[index + 1];
  const toc = post.toc.length > 2
    ? `<nav class="blog-toc" aria-label="On this page"><p>On this page</p>${post.toc.map((item) => `<a href="#${item.id}">${escape(item.text)}</a>`).join("")}</nav>`
    : "";
  const nav = older || newer
    ? `<nav class="blog-post-nav" aria-label="More posts">
          ${older ? `<a href="${older.path}"><span>Older</span>${escape(older.title)}</a>` : "<span></span>"}
          ${newer ? `<a class="newer" href="${newer.path}"><span>Newer</span>${escape(newer.title)}</a>` : "<span></span>"}
        </nav>`
    : "";
  return `
      <article class="blog-post">
        <header class="lx-hero blog-post-hero">
          <a class="lx-back" href="/blogpost/">All posts</a>
          <p class="lx-label">${meta(post)}</p>
          <h1>${escape(post.title)}</h1>
          <p class="lx-lede">${escape(post.description)}</p>
          ${tagList(post.tags)}
        </header>
        <div class="blog-layout${toc ? "" : " no-toc"}">
          ${toc}
          <div class="blog-prose">
${post.html}
          </div>
        </div>
        ${nav}
      </article>`;
}

function feed(posts) {
  const item = (post) => `    <item>
      <title>${escape(post.title)}</title>
      <link>${site}${post.path}</link>
      <guid isPermaLink="true">${site}${post.path}</guid>
      <pubDate>${new Date(`${post.date}T00:00:00Z`).toUTCString()}</pubDate>
      <description>${escape(post.description)}</description>
${post.tags.map((tag) => `      <category>${escape(tag)}</category>`).join("\n")}
    </item>`;
  return `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>${blogName}</title>
    <link>${site}/blogpost/</link>
    <atom:link href="${site}/blogpost/feed.xml" rel="self" type="application/rss+xml" />
    <description>${escape(blogDescription)}</description>
    <language>en</language>
${posts.map(item).join("\n")}
  </channel>
</rss>
`;
}

const posts = loadPosts();
const years = [...new Set(posts.map((post) => post.year))];
const outputs = new Map();
const blogPage = { "@id": `${site}/blogpost/#blog` };

outputs.set(join(outputDirectory, "index.html"), page({
  path: "/blogpost/",
  title: "Blog",
  description: blogDescription,
  content: listing("Notes from the people building LatexDo.", "Releases, how the editor and its AI work, and LaTeX writing workflows, written up as short readable posts.", posts, years),
  graph: [
    {
      "@type": "Blog",
      "@id": `${site}/blogpost/#blog`,
      url: `${site}/blogpost/`,
      name: blogName,
      description: blogDescription,
      publisher: { "@id": `${site}/#organization` },
      isPartOf: { "@id": `${site}/#website` },
      blogPost: posts.map((post) => ({ "@id": `${site}${post.path}#post` })),
    },
    breadcrumb([["Home", "/"], ["Blog", "/blogpost/"]]),
  ],
}));

for (const year of years) {
  const yearPosts = posts.filter((post) => post.year === year);
  const description = `Every post on the LatexDo blog from ${year}: releases, how the editor and its AI work, and notes on writing LaTeX.`;
  outputs.set(join(outputDirectory, year, "index.html"), page({
    path: `/blogpost/${year}/`,
    title: `Blog posts from ${year}`,
    description,
    content: listing(`Posts from ${year}.`, `${yearPosts.length} ${yearPosts.length === 1 ? "post" : "posts"} published in ${year}.`, yearPosts, years, year),
    graph: [
      { "@type": "CollectionPage", "@id": `${site}/blogpost/${year}/#webpage`, url: `${site}/blogpost/${year}/`, name: `Blog posts from ${year} - LatexDo`, description, isPartOf: blogPage },
      breadcrumb([["Home", "/"], ["Blog", "/blogpost/"], [year, `/blogpost/${year}/`]]),
    ],
  }));
}

for (const post of posts) {
  outputs.set(join(outputDirectory, post.year, post.slug, "index.html"), page({
    path: post.path,
    title: post.title,
    description: post.description,
    content: postPage(post, posts),
    article: true,
    demos: post.demos.size > 0,
    graph: [
      {
        "@type": "BlogPosting",
        "@id": `${site}${post.path}#post`,
        headline: post.title,
        description: post.description,
        datePublished: post.date,
        dateModified: post.date,
        author: { "@type": "Organization", name: post.author, url: `${site}/` },
        publisher: { "@id": `${site}/#organization` },
        image: `${site}/assets/social-preview.png`,
        keywords: post.tags.join(", "),
        mainEntityOfPage: `${site}${post.path}`,
        isPartOf: blogPage,
      },
      breadcrumb([["Home", "/"], ["Blog", "/blogpost/"], [post.year, `/blogpost/${post.year}/`], [post.title, post.path]]),
    ],
  }));
}

// Only remove pages this script generated; never overwrite handwritten ones.
function generatedPages(directory) {
  let entries;
  try { entries = readdirSync(directory, { withFileTypes: true }); } catch (error) { if (error.code === "ENOENT") return []; throw error; }
  return entries.flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return generatedPages(path);
    return entry.name === "index.html" && readFileSync(path, "utf8").includes(marker) ? [path] : [];
  });
}
const obsolete = generatedPages(outputDirectory).filter((path) => !outputs.has(path));
for (const path of outputs.keys()) {
  try {
    if (!readFileSync(path, "utf8").includes(marker)) throw new Error(`Refusing to overwrite handwritten page: ${path}`);
  } catch (error) { if (error.code !== "ENOENT") throw error; }
}

const sitemapPath = join(root, "sitemap.xml");
const sitemap = readFileSync(sitemapPath, "utf8");
const sitemapEntries = [
  ["/blogpost/", posts[0]?.date],
  ...years.map((year) => [`/blogpost/${year}/`, posts.find((post) => post.year === year).date]),
  ...posts.map((post) => [post.path, post.date]),
].map(([path, lastmod]) => `  <url>\n    <loc>${site}${path}</loc>\n${lastmod ? `    <lastmod>${lastmod}</lastmod>\n` : ""}    <changefreq>weekly</changefreq>\n    <priority>0.6</priority>\n  </url>`).join("\n");
const sitemapBlock = `  <!-- Blog: generated by scripts/build-blog.mjs -->\n${sitemapEntries}\n  <!-- /Blog -->`;
const updatedSitemap = sitemap.includes("<!-- Blog: generated")
  ? sitemap.replace(/  <!-- Blog: generated[\s\S]*?<!-- \/Blog -->/, sitemapBlock)
  : sitemap.replace("</urlset>", `${sitemapBlock}\n</urlset>`);

for (const [path, html] of outputs) {
  mkdirSync(join(path, ".."), { recursive: true });
  writeFileSync(path, html);
}
for (const path of obsolete) {
  unlinkSync(path);
  for (let directory = join(path, ".."); directory !== outputDirectory; directory = join(directory, "..")) {
    try { rmdirSync(directory); } catch { break; }
  }
}
writeFileSync(join(outputDirectory, "feed.xml"), feed(posts));
writeFileSync(sitemapPath, updatedSitemap);
console.log(`Built the blog: ${posts.length} post(s) across ${years.length} year(s).`);
