// Builds the LatexDo extension store at /store/ from store/extensions/catalog.json.
// The catalog is the same file LatexDo fetches, so the pages and the app always
// list the same extensions. Pages use the shared site template and styles.
import { mkdirSync, readFileSync, readdirSync, rmdirSync, unlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const directory = join(root, "store");
const catalogPath = join(directory, "extensions", "catalog.json");
const template = readFileSync(join(root, "scripts/volunteer-page.template.html"), "utf8");
const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));
const marker = "<!-- Generated by scripts/build-store.mjs. Edit store/extensions/catalog.json. -->";
const site = "https://latexdo.org";
const escape = (value) => String(value).replace(/[&<>"']/g, (char) => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
})[char]);

const categories = {
  writing: "Writing",
  checking: "Checking",
  bibliography: "Bibliography",
  graphics: "Figures and tables",
  templates: "Templates",
  workflow: "Workflow",
};

// Plain-language names for what an extension turns on in LatexDo.
const featureNames = {
  acronymManagerEnabled: "Acronym manager",
  autoFixCommon: "One-click fixes for common problems",
  checkAbstractWordCount: "Abstract word count",
  checkCodeLink: "Code availability link",
  checkDatasetLink: "Dataset availability link",
  checkEmbeddedFonts: "Embedded fonts check",
  checkEvaluationMetrics: "Evaluation metrics reported",
  checkFigureReferences: "Every figure is referenced",
  checkHardwareDetails: "Hardware details reported",
  checkHyperparameters: "Hyperparameters reported",
  checkLicenseMentioned: "License mentioned",
  checkPageCount: "Page limit check",
  checkRandomSeeds: "Random seeds reported",
  checkSectionsWithNoCitations: "Sections without citations",
  checkTableReferences: "Every table is referenced",
  checkType3Fonts: "Type 3 font check",
  checkUncitedCitations: "Uncited bibliography entries",
  checkUndefinedAcronym: "Undefined acronyms",
  checkUnreferencedFigures: "Unreferenced figures",
  citationAssistantEnabled: "Citation assistant",
  conferenceCheckerEnabled: "Conference submission checker",
  detectBrokenLinks: "Broken links",
  detectDuplicateReferences: "Duplicate references",
  detectMissingCitations: "Missing citations",
  detectNotation: "Notation detection",
  detectNotationConflicts: "Conflicting notation",
  detectUndefinedNotation: "Undefined notation",
  detectUnusedEntries: "Unused bibliography entries",
  errorDoctorEnabled: "Compile error doctor",
  explainErrors: "Plain-language compile errors",
  importMetadataSources: "Reference metadata import",
  notationManagerEnabled: "Notation manager",
  pdfComplianceEnabled: "PDF compliance checks",
  projectBibliographyEnabled: "Project bibliography",
  reproducibilityEnabled: "Reproducibility checklist",
  structureAssistantEnabled: "Structure assistant",
  suggestCitationKeys: "Citation key suggestions",
  suggestFixes: "Suggested fixes",
  tableGeneratorEnabled: "Visual table builder",
  tikzConverterAutoOpen: "Open the TikZ converter for new figures",
  tikzConverterEnabled: "draw.io and image to TikZ converter",
  warnOldCitations: "Old citation warnings",
};
const featureName = (flag) =>
  featureNames[flag] ?? flag.replace(/([A-Z])/g, " $1").replace(/^./, (c) => c.toUpperCase());

if (catalog?.schemaVersion !== 1 || !Array.isArray(catalog.extensions)) {
  throw new Error("store/extensions/catalog.json must be a schemaVersion 1 catalog.");
}
const ids = new Set();
for (const extension of catalog.extensions) {
  if (!/^[a-z0-9][a-z0-9.-]{2,80}$/.test(extension?.id ?? "")) {
    throw new Error(`Invalid extension id: ${extension?.id}`);
  }
  if (ids.has(extension.id)) throw new Error(`Duplicate extension id: ${extension.id}`);
  ids.add(extension.id);
  for (const field of ["name", "description", "version", "author", "category"]) {
    if (typeof extension[field] !== "string" || !extension[field].trim()) {
      throw new Error(`${extension.id}: ${field} must be a nonempty string.`);
    }
  }
  if (!categories[extension.category]) {
    throw new Error(`${extension.id}: unknown category ${extension.category}.`);
  }
  const expectedHomepage = `${site}/store/extensions/${extension.id}/`;
  if (extension.homepage !== expectedHomepage) {
    throw new Error(`${extension.id}: homepage must be ${expectedHomepage}`);
  }
}

const jsonLd = (graph) => JSON.stringify({ "@context": "https://schema.org", "@graph": graph }, null, 2)
  .replace(/</g, "\\u003c");
const breadcrumb = (items) => ({
  "@type": "BreadcrumbList",
  itemListElement: items.map(([name, path], index) => ({
    "@type": "ListItem", position: index + 1, name, item: `${site}${path}`,
  })),
});
function page(path, title, description, content, graph) {
  const values = {
    title: escape(title), description: escape(description), path: escape(path), content,
    jsonld: jsonLd(graph),
  };
  return template.replace("<!doctype html>", `<!doctype html>\n${marker}`)
    .replace(/\{\{(title|description|path|content|jsonld)\}\}/g, (_, key) => values[key]);
}
const list = (items) => `<ul class="lx-list">${items.map((item) => `<li>${escape(item)}</li>`).join("\n")}</ul>`;
const tags = (extension) => extension.tags?.length
  ? `<ul class="lx-tags" aria-label="Tags">${extension.tags.map((tag) => `<li>${escape(tag)}</li>`).join("")}</ul>`
  : "";
const extensionPath = (extension) => `/store/extensions/${extension.id}/`;
/** Search-result description: 70 to 165 characters, like every site page. */
const pageDescription = (extension) => {
  const text = extension.description.trim();
  return text.length >= 70 ? text : `${text} A free extension for the LatexDo LaTeX editor.`;
};
const kindLabel = (extension) => (extension.kind === "template" ? "Template" : "Snippet pack");

/** What installing the extension adds, in plain words. */
function additions(extension) {
  const contributes = extension.contributes ?? {};
  const items = [];
  for (const [flag, enabled] of Object.entries(contributes.featureFlags ?? {})) {
    if (enabled) items.push(featureName(flag));
  }
  for (const snippet of contributes.snippets ?? []) {
    items.push(`Snippet: ${snippet.detail || snippet.label}`);
  }
  for (const template of contributes.templates ?? []) {
    items.push(`Template: ${template.name || template.id}`);
  }
  return items;
}

const outputs = new Map();
const indexDescription =
  "Free LatexDo templates and snippet packs: IEEE and ACM papers, thesis, CV, poster, plots, tables, algorithms, math and more.";
const ordered = Object.keys(categories)
  .map((category) => [category, catalog.extensions.filter((extension) => extension.category === category)])
  .filter(([, extensions]) => extensions.length);
let number = 0;

outputs.set(join(directory, "index.html"), page("/store/", "Extension Store", indexDescription, `
      <header class="lx-hero">
        <p class="lx-label">Store</p>
        <h1>Templates and snippets for every kind of paper.</h1>
        <p class="lx-lede">
          LatexDo already includes the citation manager, table builder, TikZ converter,
          notation manager and submission checks. The store adds what it does not ship:
          venue templates, a thesis, a CV, a poster, and snippet packs for plots, tables,
          algorithms, math, chemistry, code and revisions. Everything is free.
        </p>
      </header>
      <section class="lx-rows" aria-label="Extensions">
${ordered.flatMap(([, extensions]) => extensions).map((extension) => `
        <article class="lx-row reveal">
          <span class="lx-num">${String(++number).padStart(2, "0")}</span>
          <h2><a href="${extensionPath(extension)}">${escape(extension.name)}</a></h2>
          <div class="lx-row-body">
            <p class="lx-label">${escape(categories[extension.category])}</p>
            <p>${escape(extension.description)}</p>
            ${tags(extension)}
            <a class="lx-arrow" href="${extensionPath(extension)}" aria-label="View ${escape(extension.name)}">View ${kindLabel(extension).toLowerCase()}</a>
          </div>
        </article>`).join("\n")}
      </section>
      <section class="lx-close reveal" aria-labelledby="store-close">
        <h2 id="store-close">Install from LatexDo</h2>
        <p>Open the Extensions view in LatexDo, pick a pack and choose Install. Templates appear when you create a project; snippets appear as you type.</p>
        <div class="lx-close-actions">
          <a class="lx-pill" href="/downloads/">Download LatexDo</a>
          <a class="lx-arrow" href="/store/extensions/catalog.json">Catalog (JSON)</a>
        </div>
      </section>`, [
  {
    "@type": "CollectionPage",
    "@id": `${site}/store/#webpage`,
    url: `${site}/store/`,
    name: "Extension Store - LatexDo",
    description: indexDescription,
    isPartOf: { "@id": `${site}/#website` },
  },
  breadcrumb([["Home", "/"], ["Store", "/store/"]]),
]));

for (const extension of catalog.extensions) {
  const path = extensionPath(extension);
  const added = additions(extension);
  outputs.set(join(directory, "extensions", extension.id, "index.html"), page(
    path, extension.name, pageDescription(extension), `
      <header class="lx-hero">
        <a class="lx-back" href="/store/">All extensions</a>
        <p class="lx-label">${kindLabel(extension)} · ${escape(categories[extension.category])}</p>
        <h1>${escape(extension.name)}</h1>
        <p class="lx-lede">${escape(extension.description)}</p>
      </header>
      <div class="lx-rows">
        ${added.length ? `<section class="lx-row two reveal"><h2>What it adds</h2><div class="lx-row-body">${list(added)}</div></section>` : ""}
        ${extension.tags?.length ? `<section class="lx-row two reveal"><h2>Tags</h2><div class="lx-row-body">${tags(extension)}</div></section>` : ""}
        <section class="lx-row two reveal"><h2>Details</h2><div class="lx-row-body">${list([
          `Version ${extension.version}`,
          `By ${extension.author}`,
          `Identifier ${extension.id}`,
        ])}</div></section>
      </div>
      <section class="lx-close reveal" aria-labelledby="install-title">
        <h2 id="install-title">Install ${escape(extension.name)}</h2>
        <p>In LatexDo, open the Extensions view, find ${escape(extension.name)} and choose Install. It is free.</p>
        <div class="lx-close-actions">
          <a class="lx-pill" href="/downloads/">Download LatexDo</a>
          <a class="lx-arrow" href="/store/">Browse the store</a>
        </div>
      </section>`, [
      {
        "@type": "WebPage",
        "@id": `${site}${path}#webpage`,
        url: `${site}${path}`,
        name: `${extension.name} - LatexDo`,
        description: extension.description,
        isPartOf: { "@id": `${site}/#website` },
      },
      {
        "@type": "SoftwareApplication",
        name: extension.name,
        applicationCategory: "ProductivityApplication",
        operatingSystem: "macOS, Windows, Linux",
        softwareVersion: extension.version,
        description: extension.description,
        offers: { "@type": "Offer", price: "0", priceCurrency: "EUR" },
        url: `${site}${path}`,
      },
      breadcrumb([["Home", "/"], ["Store", "/store/"], [extension.name, path]]),
    ]));
}

// Only remove pages this script generated; never overwrite handwritten ones.
const obsolete = [];
const extensionsDirectory = join(directory, "extensions");
for (const entry of readdirSync(extensionsDirectory, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const path = join(extensionsDirectory, entry.name, "index.html");
  if (outputs.has(path)) continue;
  try {
    if (readFileSync(path, "utf8").includes(marker)) obsolete.push(path);
  } catch (error) { if (error.code !== "ENOENT") throw error; }
}
for (const path of outputs.keys()) {
  try {
    if (!readFileSync(path, "utf8").includes(marker)) throw new Error(`Refusing to overwrite handwritten page: ${path}`);
  } catch (error) { if (error.code !== "ENOENT") throw error; }
}

const sitemapPath = join(root, "sitemap.xml");
const sitemap = readFileSync(sitemapPath, "utf8");
const sitemapEntries = ["/store/", ...catalog.extensions.map(extensionPath)]
  .map((path) => `  <url>\n    <loc>${site}${path}</loc>\n    <changefreq>weekly</changefreq>\n    <priority>0.6</priority>\n  </url>`).join("\n");
const sitemapBlock = `  <!-- Store: generated by scripts/build-store.mjs -->\n${sitemapEntries}\n  <!-- /Store -->`;
const updatedSitemap = sitemap.includes("<!-- Store: generated")
  ? sitemap.replace(/  <!-- Store: generated[\s\S]*?<!-- \/Store -->/, sitemapBlock)
  : sitemap.replace("</urlset>", `${sitemapBlock}\n</urlset>`);

for (const [path, html] of outputs) {
  mkdirSync(join(path, ".."), { recursive: true });
  writeFileSync(path, html);
}
for (const path of obsolete) {
  unlinkSync(path);
  try { rmdirSync(join(path, "..")); } catch { /* not empty: keep it */ }
}
writeFileSync(sitemapPath, updatedSitemap);
console.log(`Built store index and ${catalog.extensions.length} extension page(s).`);
