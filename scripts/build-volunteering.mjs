import { mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const directory = join(root, "volunteering");
const template = readFileSync(join(root, "scripts/volunteer-page.template.html"), "utf8");
const positions = JSON.parse(readFileSync(join(directory, "positions.json"), "utf8"));
const marker = "<!-- Generated by scripts/build-volunteering.mjs. Edit volunteering/positions.json. -->";
const escape = (value) => String(value).replace(/[&<>"']/g, (char) => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
})[char]);

if (!Array.isArray(positions)) throw new Error("volunteering/positions.json must contain an array.");
const slugs = new Set();
for (const position of positions) {
  if (!position || typeof position !== "object") throw new Error("Each position must be an object.");
  if (typeof position.slug !== "string" || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(position.slug)) {
    throw new Error("Each position needs a lowercase, hyphen-separated slug.");
  }
  if (slugs.has(position.slug)) throw new Error(`Duplicate position slug: ${position.slug}`);
  slugs.add(position.slug);
  if (typeof position.published !== "boolean") throw new Error(`${position.slug}: published must be true or false.`);
  if (!position.published) continue;
  for (const field of ["title", "summary", "description"]) {
    if (typeof position[field] !== "string" || !position[field].trim()) {
      throw new Error(`${position.slug}: ${field} must be a nonempty string.`);
    }
  }
  for (const field of ["languages", "responsibilities", "requirements"]) {
    if (!Array.isArray(position[field]) || !position[field].length ||
        position[field].some((item) => typeof item !== "string" || !item.trim())) {
      throw new Error(`${position.slug}: ${field} must contain nonempty strings.`);
    }
  }
  if (typeof position.applicationUrl !== "string") {
    throw new Error(`${position.slug}: applicationUrl must be a string (empty until the form is ready).`);
  }
  if (position.applicationUrl === "") continue;
  let url;
  try { url = new URL(position.applicationUrl); } catch {
    throw new Error(`${position.slug}: add a Google Form applicationUrl before publishing.`);
  }
  const isGoogleForm = (url.hostname === "forms.gle" && url.pathname.length > 1) ||
    (url.hostname === "docs.google.com" && /^\/forms\/(?:u\/\d+\/)?d\/(?:e\/)?[^/]+\/viewform$/.test(url.pathname));
  if (url.protocol !== "https:" || url.username || url.password || url.port || !isGoogleForm) {
    throw new Error(`${position.slug}: applicationUrl must be an HTTPS Google Form share link.`);
  }
}

const published = positions.filter((position) => position.published);
const outputs = new Map();
function page(path, title, description, content) {
  const values = { title: escape(title), description: escape(description), path: escape(path), content };
  return template.replace("<!doctype html>", `<!doctype html>\n${marker}`)
    .replace(/\{\{(title|description|path|content)\}\}/g, (_, key) => values[key]);
}
const list = (items) => `<ul>${items.map((item) => `<li>${escape(item)}</li>`).join("\n")}</ul>`;
const languages = (position) => `<ul class="volunteer-tags" aria-label="Languages">${position.languages.map((language) => `<li>${escape(language)}</li>`).join("")}</ul>`;
const roleIcon = `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="m8 7-5 5 5 5M16 7l5 5-5 5M14 4l-4 16" /></svg>`;

outputs.set(join(directory, "index.html"), page("/volunteering/", "Volunteering",
  "Volunteer with LatexDo and help build open-source tools for writing, education, and research.", `
      <h1 class="volunteering-title">Volunteering</h1>
      <section class="volunteer-openings" aria-label="Volunteer opportunities">
        ${published.length ? `<ul class="volunteer-list">${published.map((position) => `
          <li><a class="volunteer-card" href="/volunteering/${escape(position.slug)}/">
            <span class="volunteer-card-icon">${roleIcon}</span>
            <h2>${escape(position.title)}</h2>
            ${languages(position)}
            <span class="volunteer-card-action">View position <span aria-hidden="true">↗</span></span>
          </a></li>`).join("\n")}</ul>` : `<p>There are no open positions listed right now. Check back for future opportunities.</p>
        <p>Interested in contributing? <a href="/contact/">Get in touch</a>.</p>`}
      </section>`));

for (const position of published) {
  outputs.set(join(directory, position.slug, "index.html"), page(
    `/volunteering/${position.slug}/`, position.title, position.summary, `
      <a class="volunteer-back" href="/volunteering/">← All positions</a>
      <h1>${escape(position.title)}</h1>
      <p class="legal-intro">${escape(position.summary)}</p>
      <article class="legal-document">
        <section><h2>About the volunteer role</h2><p>${escape(position.description)}</p></section>
        <section><h2>Languages</h2>${languages(position)}</section>
        <section><h2>What you'll do</h2>${list(position.responsibilities)}</section>
        <section><h2>What you'll bring</h2>${list(position.requirements)}</section>
        <section aria-labelledby="apply-title">
          <h2 id="apply-title">Apply for this position</h2>
          ${position.applicationUrl ? `<p>Tell us about yourself and your interest in this role using our application form.</p>
          <p><a class="button primary" href="${escape(position.applicationUrl)}">Apply via Google Form <span aria-hidden="true">↗</span></a></p>
          <p>The application form is hosted on Google Forms.</p>` : `<p>The application form will be available here soon.</p>`}
        </section>
      </article>`));
}

// Only remove obsolete files that this script generated; preserve handwritten pages.
const obsolete = [];
for (const entry of readdirSync(directory, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const path = join(directory, entry.name, "index.html");
  if (outputs.has(path)) continue;
  try {
    if (readFileSync(path, "utf8").includes(marker)) obsolete.push(path);
  } catch (error) { if (error.code !== "ENOENT") throw error; }
}
for (const path of outputs.keys()) {
  try {
    if (!readFileSync(path, "utf8").includes(marker)) throw new Error(`Refusing to overwrite handwritten page: ${path}`);
  } catch (error) { if (error.code !== "ENOENT") throw error; }
}

const sitemapPath = join(root, "sitemap.xml");
const sitemap = readFileSync(sitemapPath, "utf8");
const sitemapEntries = ["/volunteering/", ...published.map((position) => `/volunteering/${position.slug}/`)]
  .map((path) => `  <url>\n    <loc>https://latexdo.org${path}</loc>\n    <changefreq>weekly</changefreq>\n    <priority>0.6</priority>\n  </url>`).join("\n");
const sitemapBlock = `  <!-- Volunteering: generated by scripts/build-volunteering.mjs -->\n${sitemapEntries}\n  <!-- /Volunteering -->`;
const updatedSitemap = sitemap.includes("<!-- Volunteering: generated")
  ? sitemap.replace(/  <!-- Volunteering: generated[\s\S]*?<!-- \/Volunteering -->/, sitemapBlock)
  : sitemap.replace("</urlset>", `${sitemapBlock}\n</urlset>`);

for (const [path, html] of outputs) {
  mkdirSync(join(path, ".."), { recursive: true });
  writeFileSync(path, html);
}
for (const path of obsolete) unlinkSync(path);
writeFileSync(sitemapPath, updatedSitemap);
console.log(`Built volunteering index and ${published.length} position page(s).`);
